function setEmojies(){
    const namelist = document.querySelector(".list-emoji");
    document.querySelector("#id_message_send-emojis").addEventListener('click', (event) => {
        event.stopPropagation();
        if (namelist.classList.contains("d-none"))
            namelist.classList.remove("d-none");
        else
            namelist.classList.add("d-none");
    });

    namelist.addEventListener('click', (event) => {
        event.stopPropagation();
    });

    document.body.addEventListener('click', () => {
        if (namelist.classList.contains("d-none"))
            return;
        namelist.classList.add("d-none");
    });

    const message = document.querySelector("#id_message_send_input");
    msEmo.forEach(emojiList => {
        let lable = document.createElement('lable');
        lable.classList.add("emoji-lable");
        lable.innerHTML = emojiList.name;

        let div = document.createElement('div');
        div.classList.add("emoji-content");
        emojiList.emojies.forEach(emoji => {
            var btn = document.createElement("span");
            btn.classList.add("emoji-button");
            btn.innerHTML = emoji;
            btn.addEventListener('click', function(event) {
                message.value += this.innerHTML;
                message.focus();
            });
            
            div.appendChild(btn);
        });
        namelist.appendChild(lable);
        namelist.appendChild(div);
    });
}

function drawtheLevel(lvl) {
    let spinner = document.getElementById("spinner");
    let ctx = spinner.getContext("2d");
    let width = spinner.width;
    let height = spinner.height;
    let degrees = 0;
    let new_degrees = (lvl/100)*180;  // % to degrees
    let color = "turquoise";
    let bgcolor = "#222";
    let animation_loop;
  
    
    function drawArc(degrees) {
      ctx.clearRect(0, 0, width, height);
  
      // Background (half-circle)
      ctx.beginPath();
      ctx.strokeStyle = bgcolor;
      ctx.lineWidth = 5;
      ctx.arc(width / 2, height, 100, Math.PI, 2 * Math.PI, false);
      ctx.stroke();
  
      // Foreground (progress)
      ctx.beginPath();
      ctx.strokeStyle = color;
      ctx.lineWidth = 5;
      let radians = degrees * Math.PI / 180;
      ctx.arc(width / 2, height, 100, Math.PI, radians + Math.PI, false);
      ctx.stroke();
  
      // Text (percentage)
      ctx.fillStyle = color;
      ctx.font = "30px Arial";
      let percentage = Math.floor(degrees / 180 * 100) + "%";
      let text_width = ctx.measureText(percentage).width;
    }
  
    function animate() {
      if (degrees < new_degrees) {
        degrees++;
        drawArc(degrees);
      } else {
        clearInterval(animation_loop);
      }
    }
  
    animation_loop = setInterval(animate, 20);
  };

